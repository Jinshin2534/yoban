// AI に渡すプロンプトの組み立て。
// git 操作を夜番側に固定するため、その約束をプロンプトに必ず添える。

export const AUTOMATION_NOTE = [
  '---',
  '（夜番からの注意。ここから下は自動実行の前提です）',
  '- この作業は無人で実行されています。確認を求めても答える人はいません。判断が必要なら最も安全な選択をしてください。',
  '- 作業ディレクトリはこのタスク専用の git worktree です。ここから出て他のディレクトリを変更しないでください。',
  '- git のコミット・push・ブランチ操作・PR 作成はしないでください。夜番が行います。ファイルの変更だけを行ってください。',
  '- 最後に、何をどう変えたかを短くまとめてください。その文章がそのまま PR の説明になります。',
].join('\n')

export function buildPrompt(task) {
  return `${String(task?.prompt ?? '').trim()}\n\n${AUTOMATION_NOTE}\n`
}
